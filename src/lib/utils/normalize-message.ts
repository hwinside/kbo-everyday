/**
 * 도배(연속 반복) 차단용 정규화 키.
 *
 * 동일 메시지 차단이 "정확 일치"이던 한계 때문에 ㄷㄷㄷ → ㄷㄷㄷㄷ → "ㄷ ㄷ ㄷ" 같은
 * 변형 도배가 전부 다른 문자열로 인식돼 뚫렸다. 비교 전에 이 함수로 정규화하면
 * 위 변형들이 같은 키로 묶여 반복 차단에 걸린다.
 *
 * 주의: 반환값은 화면에 저장/표시하지 않고 *비교 키*로만 쓴다.
 * 공격적으로 압축하므로(공백 제거 + 동일문자 런 압축) 원문 복원 용도로 쓰면 안 된다.
 *
 * 예) "ㄷㄷㄷ", "ㄷㄷㄷㄷㄷ", "ㄷ ㄷ ㄷ", "ㄷㄷㄷ!!!" → 거의 동일 키로 수렴
 */
export function normalizeForFloodKey(content: string): string {
  return content
    .trim()
    .toLowerCase()
    .replace(/\s+/g, "") // 공백/줄바꿈 제거 ("ㄷ ㄷ ㄷ" → "ㄷㄷㄷ")
    .replace(/(.)\1+/g, "$1"); // 같은 문자 연속 → 1회 ("ㄷㄷㄷㄷ" → "ㄷ")
}
