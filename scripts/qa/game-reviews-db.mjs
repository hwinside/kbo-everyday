// Reviewer-owned execution: node scripts/qa/game-reviews-db.mjs
// Isolated PostgreSQL via PGlite. No network, production credentials or real users.
// This single-connection harness does NOT claim independent-transaction race/E2E coverage.
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import { PGlite } from '@electric-sql/pglite';

const db = new PGlite();
const users = Array.from({ length: 8 }, (_, i) => `00000000-0000-4000-8000-${String(i + 1).padStart(12, '0')}`);
const [a, b, c, d, e, f] = users, game = '20260907SSLG0';
let checks = 0;
async function query(sql, args = []) { return (await db.query(sql, args)).rows; }
async function denied(action, code) { await assert.rejects(action, err => err.message.includes(code)); checks++; }
async function write(actor, op, options = {}) {
  const { rid = null, cid = null, content = null, key = content, liked = null, player = null, recreate = false, nomination = 'optional_winner_participant' } = options;
  return (await query(`SELECT gr_mutate($1,$2,$3,rid=>$4,cid=>$5,body=>$6,body_key=>$7,desired=>$8,away=>8,home=>1,winner=>1,pkey=>$9,pname=>$9,p_allow_recreate=>$10,p_nomination_mode=>$11) result`, [actor, game, op, rid, cid, content, key, liked, player, recreate, nomination]))[0].result;
}
async function feed(actor = null, before = null, parent = null, minimum = 3) { return (await query('SELECT gr_feed($1,$2,$3,$4,p_best_min_likes=>$5) result', [game, actor, before, parent, minimum]))[0].result; }
try {
  await db.exec(`CREATE ROLE anon; CREATE ROLE authenticated; CREATE ROLE service_role BYPASSRLS;
    CREATE TABLE profiles(id uuid PRIMARY KEY,team_id integer,nickname text);
    CREATE TABLE user_blocks(blocker_id uuid,blocked_id uuid);
    CREATE TABLE reports(id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,reporter_id uuid,target_type text,target_id bigint,reason text,detail text,UNIQUE(reporter_id,target_type,target_id));
    ALTER TABLE reports ENABLE ROW LEVEL SECURITY;
    GRANT USAGE ON SCHEMA public TO anon,authenticated,service_role;
    GRANT INSERT ON reports TO authenticated;
    GRANT USAGE ON SEQUENCE reports_id_seq TO authenticated;
    CREATE POLICY legacy_insert ON reports FOR INSERT TO authenticated WITH CHECK(true);
    CREATE TABLE report_blind_notices(target_type text,target_id bigint,author_id uuid,UNIQUE(target_type,target_id));`);
  await db.exec(await fs.readFile(new URL('../../supabase/migrations/20260907000001_game_reviews.sql', import.meta.url), 'utf8'));
  for (const [i, id] of users.entries()) await query('INSERT INTO profiles VALUES($1,$2,$3)', [id, [1, 8, 2, 1, 3, 4, null, 8][i], `테스트팬${i}`]);
  const first = await write(a, 'create', { content: '승리팀 한 줄', player: '출전선수' });
  const rid = first.id;
  await denied(() => write(a, 'create', { content: '중복 글' }), 'gr_exists');
  await denied(() => write(c, 'create', { content: '타팀 글' }), 'gr_team');
  await denied(() => write(users[6], 'create', { content: '미설정 글' }), 'gr_team');
  await denied(() => write(b, 'create', { content: '패배팀 선수 지정', player: '출전선수' }), 'gr_player');
  const opponent = await write(b, 'create', { content: '패배팀도 한 줄' });
  await query('UPDATE profiles SET team_id=2 WHERE id=$1', [a]);
  await write(a, 'edit', { rid, content: '수정한 한 줄', player: '출전선수' });
  assert.equal((await feed(a)).ownReview.team_id, 1); checks++;
  await denied(() => write(a, 'edit', { rid, content: '두 번째 수정' }), 'gr_edit_expired');
  await query("UPDATE game_reviews SET created_at=clock_timestamp()-interval '10 minutes' WHERE id=$1", [opponent.id]);
  await denied(() => write(b, 'edit', { rid: opponent.id, content: '기한 지난 수정' }), 'gr_edit_expired');
  await denied(() => write(c, 'delete', { rid }), 'gr_owner');
  await denied(() => write(d, 'create', { content: '필수 선수 누락', nomination: 'required_winner_participant' }), 'gr_player_required');
  await denied(() => write(d, 'create', { content: '비활성 선수 지정', nomination: 'disabled', player: '출전선수' }), 'gr_nomination_disabled');
  await denied(() => write(a, 'like', { rid, liked: true }), 'gr_self');
  for (const actor of [b, c, d]) await write(actor, 'like', { rid, liked: true });
  await write(b, 'like', { rid, liked: true }); // idempotent retry, not a toggle
  assert.equal((await feed()).best[0].like_count, 3); checks++;
  assert.equal((await feed(null, null, null, 4)).best.length, 0); checks++;
  await write(b, 'like', { rid, liked: false });
  await write(b, 'like', { rid, liked: false });
  assert.equal((await feed()).best.length, 0); checks++;
  await write(b, 'like', { rid, liked: true });
  const comment = await write(c, 'comment', { rid, content: '타팀 팬 댓글' });
  assert.equal((await feed(c, null, rid)).rows[0].content, '타팀 팬 댓글'); checks++;
  await denied(() => write(c, 'comment', { rid, content: '즉시 도배' }), 'gr_rate');
  await query("UPDATE game_review_rate_limits SET hits=ARRAY[clock_timestamp()-interval '11 seconds'] WHERE actor_id=$1 AND action='comment'", [c]);
  await denied(() => write(c, 'comment', { rid, content: '타팀 팬 댓글' }), 'gr_duplicate');
  await denied(() => write(b, 'comment_edit', { rid, cid: comment.id, content: '남의 댓글 수정' }), 'gr_owner');
  await query('INSERT INTO user_blocks VALUES($1,$2)', [a, c]);
  assert.equal((await feed(c)).rows.some(r => r.id === rid), false); checks++;
  await denied(() => feed(c, null, rid), 'gr_missing');
  await denied(() => write(c, 'like', { rid, liked: false }), 'gr_missing');
  await query('DELETE FROM user_blocks');
  await query("SELECT gr_moderate('game_review_comment',$1,true)", [comment.id]);
  assert.equal((await feed(a)).ownReview.comment_count, 0); checks++;
  await query("SELECT gr_moderate('game_review_comment',$1,false)", [comment.id]);
  assert.equal((await feed(a)).ownReview.comment_count, 1); checks++;
  // Bounded page contract over >25 children, no total comment cap.
  for (let i = 0; i < 27; i++) await query('INSERT INTO game_review_comments(review_id,author_id,content,content_key) VALUES($1,$2,$3,$3)', [rid, d, `페이지 ${i}`]);
  const page1 = await feed(a, null, rid), page2 = await feed(a, page1.next, rid);
  assert.equal(page1.rows.length, 25); assert.equal(page2.rows.length, 3);
  assert.equal(new Set([...page1.rows, ...page2.rows].map(r => r.id)).size, 28); checks++;
  for (const actor of [b, d, e]) await query("SELECT gr_report($1,'game_review',$2,'광고·도배')", [actor, rid]);
  const hidden = await feed(a);
  assert.equal(hidden.own.hidden, true); assert.equal(hidden.total, 1); assert.equal(hidden.best.length, 0); checks++;
  await denied(() => feed(b, null, rid), 'gr_missing');
  assert.equal((await query('SELECT count(*)::integer n FROM report_blind_notices'))[0].n, 1); checks++;
  await query("SELECT gr_moderate('game_review',$1,false)", [rid]);
  assert.equal((await feed()).best.length, 1); checks++;
  await denied(() => query("SELECT gr_report($1,'game_review',$2,'광고·도배')", [b, rid]), 'gr_duplicate');
  // Account deletion cascades a like, with a matching aggregate decrement.
  await query('DELETE FROM profiles WHERE id=$1', [c]);
  assert.equal((await feed(a)).ownReview.like_count, 2); checks++;
  await write(a, 'delete', { rid });
  await denied(() => write(a, 'create', { content: '삭제 후 재등록' }), 'gr_exists');
  assert.equal((await feed(a)).own.deleted, true); assert.equal((await feed()).total, 1); checks++;
  await denied(() => feed(f, null, rid), 'gr_missing');
  for (let i = 0; i < 20; i++) await write(f, 'like', { rid: opponent.id, liked: i % 2 === 0 });
  await denied(() => write(f, 'like', { rid: opponent.id, liked: true }), 'gr_rate');
  // Alternate recreate policy must create a clean NEW original, not revive old
  // reactions/comments, while the active unique index still permits only one.
  await query('UPDATE profiles SET team_id=1 WHERE id=$1', [a]);
  const renewed = await write(a, 'create', { content: '재등록 허용 정책', recreate: true });
  assert.notEqual(renewed.id, rid); assert.equal((await feed(a)).ownReview.like_count, 0); assert.equal((await feed(a)).ownReview.comment_count, 0); checks++;
  await denied(() => write(a, 'create', { content: '활성 중복', recreate: true }), 'gr_exists');
  // No client SQL/RPC bypass of API identity, final-game or content validation.
  await db.exec('SET ROLE authenticated');
  await denied(() => query('SELECT * FROM game_reviews'), 'permission denied');
  await denied(() => query('SELECT gr_feed($1,$2)', [game, a]), 'permission denied');
  await denied(() => write(d, 'create', { content: '직접 RPC 우회' }), 'permission denied');
  await denied(() => query("INSERT INTO reports(reporter_id,target_type,target_id,reason) VALUES($1,'game_review',$2,'광고·도배')", [f, opponent.id]), 'row-level security');
  await db.exec('RESET ROLE');
  console.log(JSON.stringify({ passed: checks, database: 'isolated PGlite', independentTransactionRaces: 'not covered', endUserQA: 'not covered' }));
} finally { await db.close(); }
