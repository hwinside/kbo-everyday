"""Generate comprehensive player profiles."""
import re

# Parse KBO data
with open('/tmp/all_players_data.txt', 'r') as f:
    kbo_raw = f.read()

kbo = {}
current = None
for line in kbo_raw.split('\n'):
    m = re.match(r'^=== (.+) ===$', line)
    if m:
        current = {'top10': []}
        kbo[m.group(1)] = current
        continue
    if not current: continue
    kv = re.match(r'^(.+?): (.+)$', line)
    if kv and not line.startswith('  '):
        current[kv.group(1).strip()] = kv.group(2).strip()
    t = re.match(r'^\s+(\d{4}) (.+?) (.+?) \((\d+)위\)$', line)
    if t:
        current['top10'].append(f"{t.group(1)} {t.group(2)} {t.group(3)} ({t.group(4)}위)")

def get_birth(name):
    if name in kbo:
        return kbo[name].get('생년월일', '')
    return ''

def get_hw(name):
    if name in kbo:
        return kbo[name].get('키/체중', '')
    return ''

def get_pos(name):
    if name in kbo:
        return kbo[name].get('포지션', '')
    return ''

def get_career(name):
    if name in kbo:
        return kbo[name].get('경력', '')
    return ''

def get_draft(name):
    if name in kbo:
        return kbo[name].get('드래프트', '')
    return ''

def get_top10(name):
    if name in kbo:
        return kbo[name].get('top10', [])
    return []

def top10_str(name, max_items=8):
    items = get_top10(name)
    if not items:
        return ''
    selected = items[:max_items]
    return '\\n'.join(f"• KBO TOP10: {item}" for item in selected)

