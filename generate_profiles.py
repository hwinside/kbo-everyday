# Helper to extract school path nicely
def school_path(career_str):
    """Extract school path from career string like '광주대성초-광주동성중-광주동성고-KIA'"""
    parts = career_str.split('-')
    schools = []
    for p in parts:
        p = p.strip()
        if any(x in p for x in ['초', '중', '고', '대']):
            # Remove parenthetical info
            clean = re.sub(r'\(.*?\)', '', p).strip()
            schools.append(clean)
    return ' → '.join(schools) if schools else ''

